#!/usr/bin/env python3
"""
HRBS data loader generator.

Generates LOADDATA.jcl for the six datasets that can safely
be loaded through JCL in-stream data.

INVOICE.dat is deliberately excluded because its records are
100 bytes long and must be transferred separately.
"""

import os
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(BASE_DIR, "data")
JCL_DIR = os.path.join(BASE_DIR, "jcl")

# INVOICE.dat is intentionally excluded.
DATASETS = [
    ("RESERV.dat", "&SYSUID..HRBS.RESERV.INPUT", 80, 5),
    ("FILE1.dat", "&SYSUID..HRBS.FILE1", 80, 5),
    ("FILE2.dat", "&SYSUID..HRBS.FILE2", 80, 5),
    ("TRANS.dat", "&SYSUID..HRBS.TRANS.INPUT", 80, 5),
    ("SERVICE.dat", "&SYSUID..HRBS.SERVICE.INPUT", 80, 5),
    ("RESERV_BAD.dat", "&SYSUID..HRBS.RESERV.BAD", 80, 2),
]


def generate_load_jcl():
    os.makedirs(JCL_DIR, exist_ok=True)

    lines = [
        "//HRBSLOAD JOB (ACCT),'HRBS LOAD DATA',CLASS=A,MSGCLASS=X,",
        "//             NOTIFY=&SYSUID",
        "//* HRBS DATA LOADER GENERATED BY tools/make_load_jobs.py",
        "//* INVOICE DATA MUST BE TRANSFERRED SEPARATELY",
    ]

    for idx, (fname, dsn, lrecl, trk) in enumerate(DATASETS, start=1):
        fpath = os.path.join(DATA_DIR, fname)

        if not os.path.isfile(fpath):
            raise FileNotFoundError(f"Required input file is missing: {fpath}")

        with open(fpath, "r", encoding="utf-8", newline="") as f:
            records = [
                line.rstrip("\r\n")
                for line in f
                if line.strip()
            ]

        for rec_num, record in enumerate(records, start=1):
            if len(record) > lrecl:
                raise ValueError(
                    f"{fname}, record {rec_num}: length {len(record)} "
                    f"exceeds LRECL {lrecl}"
                )

            if record.startswith("//") or record.startswith("/*"):
                raise ValueError(
                    f"{fname}, record {rec_num}: begins with a JCL control "
                    f"sequence: {record[:10]!r}"
                )

            if "\t" in record:
                raise ValueError(f"{fname}, record {rec_num}: contains a tab")

        # Pad fixed-block records to their required logical record length.
        records = [record.ljust(lrecl) for record in records]

        lines.extend([
            f"//* STEP {idx:02d}: LOAD {fname} ({len(records)} RECORDS)",
            f"//LOAD{idx:02d} EXEC PGM=IEBGENER",
            "//SYSPRINT DD SYSOUT=*",
            "//SYSIN    DD DUMMY",
            f"//SYSUT2   DD DSN={dsn},DISP=(NEW,CATLG,DELETE),",
            f"//             SPACE=(TRK,({trk},{trk}),RLSE),",
            f"//             DCB=(RECFM=FB,LRECL={lrecl},BLKSIZE=0)",
            f"//SYSUT1   DD *,DCB=(RECFM=FB,LRECL={lrecl},BLKSIZE=0)",
        ])

        lines.extend(records)
        lines.append("/*")

    out_file = os.path.join(JCL_DIR, "LOADDATA.jcl")

    with open(out_file, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    print(
        f"Generated {out_file}: {len(DATASETS)} datasets checked. "
        "INVOICE.dat is excluded."
    )


if __name__ == "__main__":
    try:
        generate_load_jcl()
    except (OSError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(1)