-- Q1 REVENUE BY ROOM TYPE
SELECT R.ROOM_TYPE, COUNT(*) AS BOOKINGS, SUM(B.TOTAL) AS REVENUE
  FROM HRBS.BILL B, HRBS.RESERVATION V, HRBS.ROOM R
 WHERE B.RES_ID = V.RES_ID AND V.ROOM_NO = R.ROOM_NO
 GROUP BY R.ROOM_TYPE;

-- Q2 UNPAID BILLS WITH GUEST NAME
SELECT B.INVOICE_ID, G.GUEST_NAME, B.TOTAL
  FROM HRBS.BILL B, HRBS.RESERVATION V, HRBS.GUEST G
 WHERE B.RES_ID = V.RES_ID AND V.GUEST_ID = G.GUEST_ID
   AND B.TOTAL > (SELECT COALESCE(SUM(P.AMOUNT),0)
                    FROM HRBS.PAYMENT P WHERE P.RES_ID = B.RES_ID);

-- Q3 ROOMS OCCUPIED ON A GIVEN DATE
SELECT V.ROOM_NO, G.GUEST_NAME, V.CHECK_IN, V.CHECK_OUT
  FROM HRBS.RESERVATION V, HRBS.GUEST G
 WHERE V.GUEST_ID = G.GUEST_ID AND V.STATUS = 'C'
   AND DATE('2026-11-12') >= V.CHECK_IN
   AND DATE('2026-11-12') <  V.CHECK_OUT;
