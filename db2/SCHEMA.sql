CREATE DATABASE HRBSDB;
CREATE TABLESPACE HRBSTS IN HRBSDB SEGSIZE 4 LOCKSIZE ANY;

CREATE TABLE HRBS.GUEST
  (GUEST_ID    CHAR(10)    NOT NULL,
   GUEST_NAME  VARCHAR(30) NOT NULL,
   PHONE       CHAR(10),
   CITY        VARCHAR(20),
   PRIMARY KEY (GUEST_ID))
  IN HRBSDB.HRBSTS;
CREATE UNIQUE INDEX HRBS.IXGUEST ON HRBS.GUEST (GUEST_ID);

CREATE TABLE HRBS.ROOM
  (ROOM_NO         CHAR(4)      NOT NULL,
   ROOM_TYPE       CHAR(3)      NOT NULL,
   RATE_PER_NIGHT  DECIMAL(8,2) NOT NULL,
   STATUS          CHAR(1)      NOT NULL WITH DEFAULT 'A',
   PRIMARY KEY (ROOM_NO))
  IN HRBSDB.HRBSTS;
CREATE UNIQUE INDEX HRBS.IXROOM ON HRBS.ROOM (ROOM_NO);

CREATE TABLE HRBS.RESERVATION
  (RES_ID        CHAR(8)   NOT NULL,
   GUEST_ID      CHAR(10)  NOT NULL,
   ROOM_NO       CHAR(4)   NOT NULL,
   CHECK_IN      DATE      NOT NULL,
   CHECK_OUT     DATE      NOT NULL,
   NO_OF_GUESTS  SMALLINT  NOT NULL,
   STATUS        CHAR(1)   NOT NULL WITH DEFAULT 'C',
   PRIMARY KEY (RES_ID),
   FOREIGN KEY (GUEST_ID) REFERENCES HRBS.GUEST,
   FOREIGN KEY (ROOM_NO)  REFERENCES HRBS.ROOM)
  IN HRBSDB.HRBSTS;
CREATE UNIQUE INDEX HRBS.IXRESV ON HRBS.RESERVATION (RES_ID);

CREATE TABLE HRBS.BILL
  (INVOICE_ID      CHAR(8)       NOT NULL,
   RES_ID          CHAR(8)       NOT NULL,
   BILL_DATE       DATE          NOT NULL,
   NIGHTS          SMALLINT      NOT NULL,
   ROOM_CHARGE     DECIMAL(10,2) NOT NULL,
   SERVICE_CHARGE  DECIMAL(10,2) NOT NULL,
   TAX             DECIMAL(10,2) NOT NULL,
   TOTAL           DECIMAL(12,2) NOT NULL,
   PAY_STATUS      CHAR(1)       NOT NULL WITH DEFAULT 'P',
   PRIMARY KEY (INVOICE_ID),
   FOREIGN KEY (RES_ID) REFERENCES HRBS.RESERVATION)
  IN HRBSDB.HRBSTS;
CREATE UNIQUE INDEX HRBS.IXBILL ON HRBS.BILL (INVOICE_ID);

CREATE TABLE HRBS.PAYMENT
  (PAYMENT_ID  CHAR(8)       NOT NULL,
   RES_ID      CHAR(8)       NOT NULL,
   PAY_DATE    DATE          NOT NULL,
   PAY_MODE    CHAR(3)       NOT NULL,
   AMOUNT      DECIMAL(12,2) NOT NULL,
   PRIMARY KEY (PAYMENT_ID),
   FOREIGN KEY (RES_ID) REFERENCES HRBS.RESERVATION)
  IN HRBSDB.HRBSTS;
CREATE UNIQUE INDEX HRBS.IXPAY ON HRBS.PAYMENT (PAYMENT_ID);

